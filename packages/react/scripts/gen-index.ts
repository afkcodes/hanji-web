/**
 * Generate src/components/index.ts from the component folders, so parallel work never edits a
 * shared barrel. Each folder's own index.ts decides what it exports.
 */
import { existsSync, readdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'components');
const dirs = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(root, d.name, 'index.ts')))
  .map((d) => d.name)
  .toSorted();
const body = `// Generated by scripts/gen-index.ts — do not edit.\n${dirs.map((d) => `export * from './${d}/index.ts';`).join('\n')}\n`;
const file = join(root, 'index.ts');
if (!existsSync(file) || readFileSync(file, 'utf8') !== body) {
  // atomic: parallel runs never leave a half-written barrel
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, body);
  renameSync(tmp, file);
}
console.log(`components: ${dirs.length}`);
